import { browserTransport, createApi, SERVER_PREFIX, type ApiOptions } from "../../../../client/api";
import type { VersionsPage } from "../../../../client/consultation-records";
import { matchesSchema, type Schema } from "../../../../client/schema-check";
import { readWorkMilestones, type WorkMilestone } from "../../../../client/work-milestones";

const closed = (properties: Record<string, Schema>): Schema => ({
  type: "object", properties, required: Object.keys(properties), additionalProperties: false,
});
const text = { type: "string" } as const;
const instant = { type: "string", format: "date-time" } as const;
const nullable = (schema: Schema): Schema => ({ anyOf: [schema, { type: "null" }] });
const values = (...options: string[]): Schema => ({ anyOf: options.map((value) => ({ const: value })) });
const list = (items: Schema): Schema => ({ type: "array", items });

export type Slot = {
  id: string;
  startsAt: string;
  proposedAt: string;
  state: "requested" | "countered" | "confirmed";
};
export type RosterStudent = {
  studentId: string;
  givenName: string | null;
  familyName: string | null;
  groupName: string | null;
  assignments: {
    assignmentId: string;
    documentId: string | null;
    workState: "not_started" | "in_progress" | "submitted";
  }[];
};

// These projections are present in the server contracts, ahead of the web bundle.
// Keep the closed shapes local until the shared client is regenerated by its owner.
const slots = list(closed({
  id: text, startsAt: instant, proposedAt: instant, state: values("requested", "countered", "confirmed"),
}));
const students = list(closed({
  studentId: text, givenName: nullable(text), familyName: nullable(text), groupName: nullable(text),
  assignments: list(closed({
    assignmentId: text, documentId: nullable(text), workState: values("not_started", "in_progress", "submitted"),
  })),
}));

async function readProjection<K extends string, T>(
  path: string, key: K, schema: Schema, options: ApiOptions,
): Promise<T[] | null> {
  try {
    const url = new URL(SERVER_PREFIX + path, options.baseUrl ?? globalThis.location.origin);
    const response = await (options.fetchImpl ?? browserTransport)(url, {
      method: "GET", credentials: "include", redirect: "manual", cache: "no-store",
      headers: { accept: "application/json" },
    });
    if (response.status !== 200 || !/^application\/json(?:\s*;|$)/i.test(response.headers.get("content-type") ?? "")) return null;
    const body: unknown = await response.json();
    return matchesSchema(closed({ [key]: schema }), body) ? (body as Record<K, T[]>)[key] : null;
  } catch {
    return null;
  }
}

export async function readMilestones(id: string, options: ApiOptions = {}) {
  try {
    const answer = await readWorkMilestones(id, createApi(options));
    return answer.ok ? answer.body.milestones : null;
  } catch {
    return null;
  }
}

export function readSlots(id: string, options: ApiOptions = {}) {
  return readProjection<"slots", Slot>(`works/${encodeURIComponent(id)}/consultation-slots`, "slots", slots, options);
}

export function readRoster(id: string, options: ApiOptions = {}) {
  return readProjection<"students", RosterStudent>(`teacher/courses/${encodeURIComponent(id)}/students`, "students", students, options);
}

type Version = VersionsPage["versions"][number];
export type TimelineEvent =
  | { key: string; at: string; kind: "milestone"; title: string }
  | { key: string; at: string; kind: "request" | "confirmed" | "countered" | "requested" }
  | { key: string; at: string; kind: Version["kind"]; revision: number };

export function timelineEvents(
  milestones: readonly WorkMilestone[], slots: readonly Slot[], versions: readonly Version[],
): TimelineEvent[] {
  const events: TimelineEvent[] = [];
  for (const step of milestones) {
    if (step.dueAt) events.push({ key: `milestone:${step.id}`, at: step.dueAt, kind: "milestone", title: step.title });
  }
  for (const slot of slots) {
    events.push({ key: `request:${slot.id}`, at: slot.proposedAt, kind: "request" });
    events.push({ key: `slot:${slot.id}`, at: slot.startsAt, kind: slot.state });
  }
  for (const version of versions) {
    events.push({
      key: `${version.kind}:${version.revision}`, at: version.savedMinute, kind: version.kind, revision: version.revision,
    });
  }
  return events.sort((a, b) => Date.parse(a.at) - Date.parse(b.at));
}

export function workStatus(submitted: boolean | undefined, versions: VersionsPage | null | undefined) {
  if (submitted || versions?.versions.some((version) => version.kind === "submission")) return "submitted";
  if (submitted === false || versions) return "inProgress";
  return versions === undefined ? "loading" : "unavailable";
}
